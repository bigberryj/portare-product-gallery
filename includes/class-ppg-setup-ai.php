<?php
/**
 * Product setup AI motion generation.
 *
 * Server-side controller for the Wan image-to-video provider. The API
 * credential stays on the server: it is read from a PHP constant, the site's
 * runtime environment helper, or the process environment, and it is never
 * emitted into markup, JSON payloads or browser assets.
 *
 * Safety model:
 * - Every call is nonce and capability checked against the product.
 * - The operator must approve sending the selected setup images to the
 *   provider on each generation request, because the render is paid for.
 * - A job row is written before the paid provider call, so a closed tab or a
 *   restarted container cannot lose the render.
 * - Generated bytes are validated (container signature, sniffed MIME, real
 *   duration and frame size) before they enter the Media Library, and rejected
 *   bytes are deleted.
 * - A generated clip is a draft attachment. It is published only when the
 *   operator selects it and saves the product normally. This controller never
 *   writes product metadata.
 *
 * @package PortareProductGallery
 */

defined('ABSPATH') || exit;

class PPG_Setup_AI {
    /** Minimum number of frames the provider needs. */
    const MIN_IMAGES = 2;

    /** Maximum number of frames the provider accepts. */
    const MAX_IMAGES = 2;

    /** Minimum interval between two health probes of one user, in seconds. */
    const HEALTH_RATE_SECONDS = 60;

    public static function init() {
        add_action('wp_ajax_ppg_setup_ai_generate', array(__CLASS__, 'ajax_generate'));
        add_action('wp_ajax_ppg_setup_ai_status', array(__CLASS__, 'ajax_status'));
        add_action('wp_ajax_ppg_setup_ai_health', array(__CLASS__, 'ajax_health'));
    }

    /* -------------------------------------------------------------- config */

    /**
     * Provider configuration.
     *
     * Precedence: PHP constant, process environment, then the
     * `ppg_setup_ai_config` filter. The credential is never returned to the
     * browser; `public_config()` exposes only the non-secret values.
     *
     * @return array
     */
    public static function config() {
        $config = class_exists('PPG_Wan') ? PPG_Wan::config() : array('key' => '', 'site' => '');
        if (function_exists('apply_filters')) {
            $filtered = apply_filters('ppg_setup_ai_config', $config);
            if (is_array($filtered)) { $config = array_merge($config, $filtered); }
        }
        $config['key'] = is_string($config['key']) ? trim($config['key']) : '';
        $config['enabled'] = $config['key'] !== '';
        return $config;
    }

    /**
     * Non-secret configuration for the editor UI.
     *
     * The reason a site is disabled distinguishes a missing credential from a
     * missing runtime. No provider call is made to build this value, so the
     * admin screen still renders on a server that has no runtime installed.
     *
     * @return array
     */
    public static function public_config() {
        if (class_exists('PPG_Wan')) { return PPG_Wan::public_config(); }
        return array(
            'enabled' => false,
            'provider' => 'Wan',
            'message' => 'AI motion generation is not configured on this site.',
            'reason' => 'runtime_missing',
            'duration' => 5,
            'durations' => array(5, 10, 15),
            'resolutions' => array('480P', '720P'),
            'minImages' => self::MIN_IMAGES,
            'maxImages' => self::MAX_IMAGES,
            'maxPrompt' => 500,
            'runtimeReady' => false,
        );
    }

    /** Prompt used when the operator leaves the field empty. */
    public static function default_prompt() {
        return class_exists('PPG_Wan') ? PPG_Wan::default_prompt() : '';
    }

    /* --------------------------------------------------------------- input */

    /** Plain-text prompt, length bounded, markup stripped. */
    public static function sanitize_prompt($raw) {
        if (!class_exists('PPG_Wan')) { return ''; }
        return PPG_Wan::sanitize_prompt($raw);
    }

    /* -------------------------------------------------------------- request */

    /**
     * Build one error result.
     *
     * Extra fields are merged into the response body, so a caller can pass
     * the job id or other context along. The code and the message always
     * stay authoritative.
     *
     * @param int    $status  HTTP status.
     * @param string $code    Machine readable code.
     * @param string $message Operator facing message.
     * @param array  $extra   Extra body fields.
     * @return array
     */
    private static function invalid($status, $code, $message, $extra = array()) {
        $body = array();
        if (is_array($extra)) {
            foreach ($extra as $key => $value) {
                if (!is_string($key) || $key === '') { continue; }
                if (is_scalar($value) || $value === null) { $body[$key] = $value; }
            }
        }
        $body['code'] = $code;
        $body['message'] = $message;
        return array('ok' => false, 'status' => $status, 'code' => $code, 'message' => $message, 'body' => $body);
    }

    /** Admin AJAX endpoint for one AI action. */
    public static function ajax_url($action) {
        return function_exists('admin_url') ? admin_url('admin-ajax.php') : '';
    }

    /** Nonce for the AI endpoints of one product. */
    public static function nonce($product_id) {
        return function_exists('wp_create_nonce') ? wp_create_nonce('ppg_setup_ai_' . (int) $product_id) : '';
    }

    /**
     * Shared request guards for both AI endpoints.
     *
     * @return int|array The product id when the request may proceed, or a
     *                   structured error result.
     */
    private static function guard($action) {
        $product_id = self::positive_id($_POST['product_id'] ?? null);
        if (!$product_id || get_post_type($product_id) !== 'product') {
            return self::invalid(400, 'invalid_product', 'The product could not be verified.');
        }
        if (!current_user_can('edit_post', $product_id) || !current_user_can('upload_files')) {
            return self::invalid(403, 'forbidden', 'You are not allowed to generate setup media for this product.');
        }
        $nonce = $_POST['nonce'] ?? '';
        if (!is_string($nonce) || !wp_verify_nonce(wp_unslash($nonce), 'ppg_setup_ai_' . $product_id)) {
            return self::invalid(403, 'invalid_nonce', 'The request expired. Reload the product and try again.');
        }
        return $product_id;
    }

    /* ------------------------------------------------------------- generate */

    public static function ajax_generate() {
        $result = self::handle_generate();
        if ($result['status'] === 200) {
            if (function_exists('wp_send_json_success')) { wp_send_json_success($result['body']); }
            return;
        }
        if (function_exists('wp_send_json_error')) { wp_send_json_error($result['body'], $result['status']); }
    }

    /**
     * Start one AI motion render.
     *
     * @return array Structured outcome for the JSON transport.
     */
    public static function handle_generate() {
        $product_id = self::guard('generate');
        if (is_array($product_id)) { return $product_id; }

        $config = self::config();
        if (!$config['enabled']) {
            return self::invalid(503, 'provider_not_configured', 'AI motion generation is not configured on this site.');
        }
        if (!class_exists('PPG_Wan')) {
            return self::invalid(503, 'provider_not_configured', 'AI motion generation is not configured on this site.');
        }

        // The operator must approve the paid render and the external image
        // transfer on each request.
        $consent = isset($_POST['consent']) ? (string) wp_unslash($_POST['consent']) : '';
        if ($consent !== '1') {
            return self::invalid(403, 'consent_required', 'Approve sending the setup images to the AI provider before generating.');
        }

        $frames = PPG_Wan::validate_frames($_POST['first_frame_id'] ?? null, $_POST['last_frame_id'] ?? null);
        if (!$frames['ok']) {
            return self::invalid(400, $frames['code'], $frames['message']);
        }

        $duration_error = 0;
        $duration = PPG_Wan::sanitize_duration($_POST['duration'] ?? null, $duration_error);
        if ($duration_error) {
            return self::invalid(400, 'invalid_duration', 'Choose a clip duration of 5, 10 or 15 seconds.');
        }
        $resolution_error = 0;
        $resolution = PPG_Wan::sanitize_resolution($_POST['resolution'] ?? null, $resolution_error);
        if ($resolution_error) {
            return self::invalid(400, 'invalid_resolution', 'Choose a clip resolution of 480P or 720P.');
        }

        $prompt = self::sanitize_prompt($_POST['prompt'] ?? '');
        if ($prompt === '') { $prompt = self::default_prompt(); }

        $first_path = PPG_Wan::frame_path($frames['first']);
        $last_path = PPG_Wan::frame_path($frames['last']);
        if ($first_path === '' || $last_path === '') {
            return self::invalid(400, 'invalid_frames', 'One of the selected frames is not available as a file on this server.');
        }

        $user_id = (int) get_current_user_id();

        // The submission lock covers the whole request, so two operators
        // cannot start two paid renders for the same product.
        $lock = PPG_Wan::acquire_lock(PPG_Wan::SUBMIT_LOCK_PREFIX, $product_id, PPG_Wan::LOCK_TTL);
        if ($lock === false) {
            return self::invalid(409, 'already_running', 'A setup clip is already being generated for this product.');
        }

        try {
            // Pruning happens under the lock, so a concurrent submission
            // cannot drop the job row this request is about to write.
            PPG_Wan::prune_jobs($product_id);

            // At most one paid render may be in flight for one product,
            // across every user.
            $active = PPG_Wan::active_jobs($product_id);
            if (count($active) >= PPG_Wan::MAX_ACTIVE_JOBS) {
                $own = null;
                foreach ($active as $candidate) {
                    if ((int) $candidate['user_id'] === $user_id) { $own = $candidate; break; }
                }
                $extra = $own ? array('job_id' => $own['id']) : array();
                return self::invalid(409, 'already_running', 'A setup clip is already being generated for this product.', $extra);
            }

            // The job row is written before the paid call so the render is
            // never lost, and the write itself is checked.
            $job = array(
                'id' => PPG_Wan::job_id(),
                'product_id' => (int) $product_id,
                'user_id' => $user_id,
                'status' => 'submitted',
                'task_id' => '',
                'attachment_id' => 0,
                'url' => '',
                'error' => '',
                'prompt' => $prompt,
                'duration' => (int) $duration,
                'resolution' => (string) $resolution,
                'first_frame_id' => (int) $frames['first'],
                'last_frame_id' => (int) $frames['last'],
                'created' => time(),
                'updated' => time(),
            );
            if (!PPG_Wan::save_job($job)) {
                return self::invalid(500, 'job_not_stored', 'The generation job could not be recorded, so no render was started.');
            }
            // The index must point at the job before the provider is called.
            // Without it a lost render could never be recovered.
            if (!PPG_Wan::remember_job($product_id, $job['id'])) {
                return self::invalid(500, 'job_not_stored', 'The generation job could not be recorded, so no render was started.');
            }

            $response = PPG_Wan::run('create', array(
                'first_frame' => $first_path,
                'last_frame' => $last_path,
                'duration' => (int) $duration,
                'resolution' => (string) $resolution,
                'prompt' => $prompt,
            ));

            if (!$response['ok']) {
                // A transport failure is ambiguous: the provider may have
                // accepted the render. The job is preserved as unknown and
                // must never be resubmitted automatically. The runner's own
                // verdict wins, and an unknown failure code is ambiguous.
                $ambiguous = array_key_exists('ambiguous', $response)
                    ? (bool) $response['ambiguous']
                    : PPG_Wan::is_ambiguous_failure($response['code']);
                $job['status'] = $ambiguous ? 'unknown' : 'failed';
                $job['error'] = PPG_Wan::scrub($response['message'], $config['key']);
                $job['updated'] = time();
                PPG_Wan::save_job($job);

                if ($ambiguous) {
                    return self::invalid(502, 'provider_ambiguous', 'The AI provider did not confirm the request. The render may still be running; check the status before starting another one.', array('job_id' => $job['id']));
                }
                return self::invalid(502, 'provider_error', $job['error'], array('job_id' => $job['id']));
            }

            $task_id = isset($response['data']['task_id']) ? (string) $response['data']['task_id'] : '';
            if ($task_id === '') {
                $job['status'] = 'unknown';
                $job['error'] = 'The AI provider did not return a task reference.';
                $job['updated'] = time();
                PPG_Wan::save_job($job);
                return self::invalid(502, 'provider_ambiguous', 'The AI provider did not return a task reference. Check the status before starting another render.', array('job_id' => $job['id']));
            }

            // The task reference is persisted immediately, so a restart
            // cannot lose the ability to poll for the result.
            $job['status'] = 'processing';
            $job['task_id'] = $task_id;
            $job['updated'] = time();
            if (!PPG_Wan::save_job($job)) {
                // The provider accepted the render but the task reference
                // could not be stored. The job is kept as unknown so it is
                // never resubmitted automatically.
                $job['status'] = 'unknown';
                $job['error'] = 'The provider accepted the render, but the task reference could not be stored.';
                $job['updated'] = time();
                PPG_Wan::save_job($job);
                return self::invalid(502, 'provider_ambiguous', 'The AI provider accepted the request, but the job could not be updated. Check the status before starting another render.', array('job_id' => $job['id']));
            }

            return array('ok' => true, 'status' => 200, 'code' => 'ok', 'message' => '', 'body' => array(
                'job_id' => $job['id'],
                'status' => 'processing',
                'attachment_id' => 0,
                'url' => '',
                'message' => 'The AI provider is rendering the setup clip.',
                'settings' => array(
                    'duration' => (int) $duration,
                    'resolution' => (string) $resolution,
                ),
            ));
        } finally {
            PPG_Wan::release_lock(PPG_Wan::SUBMIT_LOCK_PREFIX, $product_id, $lock);
        }
    }

    /* --------------------------------------------------------------- status */

    public static function ajax_status() {
        $result = self::handle_status();
        if ($result['status'] === 200) {
            if (function_exists('wp_send_json_success')) { wp_send_json_success($result['body']); }
            return;
        }
        if (function_exists('wp_send_json_error')) { wp_send_json_error($result['body'], $result['status']); }
    }

    /**
     * Poll one job and store the finished clip in the Media Library.
     *
     * The response body always carries the job state, so the editor can
     * resume, wait or stop without ever starting a second paid render.
     *
     * @return array Structured outcome for the JSON transport.
     */
    public static function handle_status() {
        $product_id = self::guard('status');
        if (is_array($product_id)) { return $product_id; }

        $user_id = (int) get_current_user_id();
        $raw_job_id = $_POST['job_id'] ?? '';
        if (is_array($raw_job_id)) {
            return self::invalid(400, 'invalid_job_id', 'That generation job reference is not valid.');
        }
        $raw_job_id = is_string($raw_job_id) ? trim($raw_job_id) : '';
        $job_id = self::sanitize_job_id($raw_job_id);
        if ($job_id === '' && $raw_job_id !== '') {
            // A malformed reference is refused. It is not treated as an
            // absent reference, so a typo can never look like "nothing to
            // resume" and hide a running render.
            return self::invalid(400, 'invalid_job_id', 'That generation job reference is not valid.');
        }
        if ($job_id === '') {
            // Recovery: resume the newest job this user owns for this
            // product.
            $job = self::latest_job_for_user($product_id, $user_id);
            if (!$job) {
                return self::status_body(array(
                    'job_id' => '',
                    'status' => 'idle',
                    'message' => 'There is no AI render for this product to resume.',
                ));
            }
        } else {
            $job = PPG_Wan::load_job($job_id);
        }
        if (!$job || (int) $job['product_id'] !== (int) $product_id || (int) $job['user_id'] !== $user_id) {
            return self::invalid(404, 'unknown_job', 'That generation job is no longer available.');
        }

        if ($job['status'] === 'failed') {
            return self::status_body(array(
                'job_id' => $job['id'],
                'status' => 'failed',
                'message' => $job['error'] !== '' ? $job['error'] : 'The AI provider could not render this clip.',
            ));
        }
        if ($job['status'] === 'unknown') {
            // The render may or may not have started. It is never resubmitted.
            return self::status_body(array(
                'job_id' => $job['id'],
                'status' => 'unknown',
                'message' => $job['error'] !== '' ? $job['error'] : 'The result of the last render request is not known. Do not start another render.',
            ));
        }
        if ($job['status'] === 'succeeded') {
            return self::status_body(array(
                'job_id' => $job['id'],
                'status' => 'succeeded',
                'attachment_id' => (int) $job['attachment_id'],
                'url' => (string) $job['url'],
                'message' => 'The AI setup clip is ready in the Media Library.',
                'settings' => self::job_settings($job),
            ));
        }

        $config = self::config();
        if (!$config['enabled']) {
            return self::invalid(503, 'provider_not_configured', 'AI motion generation is not configured on this site.');
        }
        if ($job['task_id'] === '') {
            // An ambiguous submission has no task reference to poll. The
            // operator has to reconcile the render against the provider
            // account history by hand.
            return self::status_body(array(
                'job_id' => $job['id'],
                'status' => 'unknown',
                'message' => 'The AI provider never confirmed this render, so it cannot be resumed automatically. Check the Wan account history for this request before starting another render.',
            ));
        }

        // Serialize status reads and writes as well as import. Otherwise a
        // slow failed/nonterminal poll can overwrite a completed job.
        $lock = PPG_Wan::acquire_lock(PPG_Wan::IMPORT_LOCK_PREFIX, $job['id'], PPG_Wan::IMPORT_LOCK_TTL);
        if ($lock === false) {
            return self::status_body(array(
                'job_id' => $job['id'],
                'status' => 'processing',
                'message' => 'The AI setup clip status is being checked or imported.',
                'settings' => self::job_settings($job),
            ));
        }

        try {
            // The job is read again inside the lock. A request that polled
            // before this one finished can otherwise import the same clip a
            // second time.
            $fresh = PPG_Wan::load_job($job['id']);
            if (is_array($fresh) && (int) $fresh['product_id'] === (int) $product_id && (int) $fresh['user_id'] === $user_id) {
                $job = $fresh;
                if ($job['status'] === 'succeeded') {
                    return self::status_body(array(
                        'job_id' => $job['id'],
                        'status' => 'succeeded',
                        'attachment_id' => (int) $job['attachment_id'],
                        'url' => (string) $job['url'],
                        'message' => 'The AI setup clip is ready in the Media Library.',
                        'settings' => self::job_settings($job),
                    ));
                }
                if ($job['status'] === 'failed') {
                    return self::status_body(array(
                        'job_id' => $job['id'],
                        'status' => 'failed',
                        'message' => $job['error'] !== '' ? $job['error'] : 'The AI provider could not render this clip.',
                    ));
                }
            }

            $response = PPG_Wan::run('status', array('task_id' => (string) $job['task_id']));
            if (!$response['ok']) {
                $job['updated'] = time();
                $job['error'] = PPG_Wan::scrub($response['message'], $config['key']);
                PPG_Wan::save_job($job);
                return self::invalid(502, 'provider_error', $job['error'], array('job_id' => $job['id']));
            }

            $status = isset($response['data']['status']) ? (string) $response['data']['status'] : 'processing';

            if ($status === 'failed') {
                $reason = isset($response['data']['error']) ? (string) $response['data']['error'] : '';
                $job['status'] = 'failed';
                $job['error'] = $reason !== '' ? $reason : 'The AI provider could not render this clip.';
                $job['updated'] = time();
                PPG_Wan::save_job($job);
                return self::status_body(array(
                    'job_id' => $job['id'],
                    'status' => 'failed',
                    'message' => $job['error'],
                ));
            }

            if ($status !== 'succeeded') {
                // A poll that started before the clip was stored must not
                // overwrite a finished state with "processing".
                $fresh = PPG_Wan::load_job($job['id']);
                if (is_array($fresh) && $fresh['status'] === 'succeeded') {
                    return self::status_body(array(
                        'job_id' => $fresh['id'],
                        'status' => 'succeeded',
                        'attachment_id' => (int) $fresh['attachment_id'],
                        'url' => (string) $fresh['url'],
                        'message' => 'The AI setup clip is ready in the Media Library.',
                        'settings' => self::job_settings($fresh),
                    ));
                }
                if (is_array($fresh) && $fresh['status'] === 'failed') {
                    return self::status_body(array(
                        'job_id' => $fresh['id'],
                        'status' => 'failed',
                        'message' => $fresh['error'] !== '' ? $fresh['error'] : 'The AI provider could not render this clip.',
                    ));
                }
                $job['status'] = 'processing';
                $job['updated'] = time();
                PPG_Wan::save_job($job);
                return self::status_body(array(
                    'job_id' => $job['id'],
                    'status' => 'processing',
                    'message' => 'The AI provider is still rendering the setup clip.',
                    'settings' => self::job_settings($job),
                ));
            }

            $download_url = isset($response['data']['download_url']) ? (string) $response['data']['download_url'] : '';
            $stored = PPG_Wan::store_generated_video($download_url, (int) $product_id, $job['id']);
            if (!$stored['ok']) {
                $job['status'] = 'failed';
                $job['error'] = $stored['message'];
                $job['updated'] = time();
                PPG_Wan::save_job($job);
                return self::status_body(array(
                    'job_id' => $job['id'],
                    'status' => 'failed',
                    'message' => $job['error'],
                ));
            }

            $job['status'] = 'succeeded';
            $job['attachment_id'] = (int) $stored['attachment_id'];
            $job['url'] = (string) $stored['url'];
            $job['error'] = '';
            $job['updated'] = time();
            if (!PPG_Wan::save_job($job)) {
                // The clip is in the Media Library and is tagged with the
                // job id. The stored state is reconciled from that tag, so
                // the clip is never imported or downloaded a second time.
                $existing = PPG_Wan::find_attachment_for_job($job['id']);
                if ($existing) {
                    $job['attachment_id'] = $existing;
                    $job['url'] = function_exists('wp_get_attachment_url') ? (string) wp_get_attachment_url($existing) : '';
                    PPG_Wan::save_job($job);
                }
                return self::status_body(array(
                    'job_id' => $job['id'],
                    'status' => 'succeeded',
                    'attachment_id' => (int) $job['attachment_id'],
                    'url' => (string) $job['url'],
                    'message' => 'The AI setup clip is ready in the Media Library.',
                    'settings' => self::job_settings($job),
                ));
            }

            return self::status_body(array(
                'job_id' => $job['id'],
                'status' => 'succeeded',
                'attachment_id' => (int) $stored['attachment_id'],
                'url' => (string) $stored['url'],
                'message' => 'The AI setup clip is ready in the Media Library.',
                'settings' => self::job_settings($job),
            ));
        } finally {
            PPG_Wan::release_lock(PPG_Wan::IMPORT_LOCK_PREFIX, $job['id'], $lock);
        }
    }

    /**
     * Wrap a status body in the transport envelope.
     *
     * @return array
     */
    private static function status_body(array $body) {
        if (!array_key_exists('attachment_id', $body)) { $body['attachment_id'] = 0; }
        if (!array_key_exists('url', $body)) { $body['url'] = ''; }
        return array('ok' => true, 'status' => 200, 'code' => 'ok', 'message' => '', 'body' => $body);
    }

    /* --------------------------------------------------------------- health */

    public static function ajax_health() {
        $result = self::handle_health();
        if ($result['status'] === 200) {
            if (function_exists('wp_send_json_success')) { wp_send_json_success($result['body']); }
            return;
        }
        if (function_exists('wp_send_json_error')) { wp_send_json_error($result['body'], $result['status']); }
    }

    /**
     * Read-only provider probe.
     *
     * It reports whether the credential and the runtime are usable. It never
     * submits a render and never spends credit.
     *
     * The probe is guarded like the other endpoints: a product id, the
     * per-product nonce and the edit capability are all required, so the
     * endpoint cannot be used to make this server talk to the provider from
     * another site. A rate bound keeps repeated probes from turning into a
     * stream of provider calls.
     *
     * @return array Structured outcome for the JSON transport.
     */
    public static function handle_health() {
        $product_id = self::guard('health');
        if (is_array($product_id)) { return $product_id; }

        if (!class_exists('PPG_Wan')) {
            return self::invalid(503, 'provider_not_configured', 'AI motion generation is not configured on this site.');
        }
        $config = self::config();
        if (!$config['enabled']) {
            return self::invalid(503, 'provider_not_configured', 'AI motion generation is not configured on this site.');
        }
        if (!self::health_rate_ok($product_id, (int) get_current_user_id())) {
            return self::invalid(429, 'too_many_health_checks', 'The provider status was checked very recently. Wait a moment before checking again.');
        }
        $response = PPG_Wan::run('health', array());
        if (!$response['ok']) {
            return self::invalid(502, 'provider_error', PPG_Wan::scrub($response['message'], $config['key']));
        }
        return array('ok' => true, 'status' => 200, 'code' => 'ok', 'message' => '', 'body' => array(
            'enabled' => !empty($response['data']['enabled']),
            'message' => isset($response['data']['message']) ? (string) $response['data']['message'] : '',
        ));
    }

    /**
     * Rate bound for the health probe.
     *
     * One probe per user and product per interval is enough for the editor.
     * The counter is an option, so it survives the request without a
     * database table.
     *
     * @param int $product_id Product id.
     * @param int $user_id    User id.
     * @return bool
     */
    private static function health_rate_ok($product_id, $user_id) {
        $key = '_ppg_ai_health_' . (int) $product_id . '_' . (int) $user_id;
        $now = time();
        $last = get_option($key, 0);
        if (is_numeric($last) && $now - (int) $last < self::HEALTH_RATE_SECONDS) {
            return false;
        }
        update_option($key, $now, false);
        return true;
    }

    /* ------------------------------------------------------------- helpers */

    /**
     * The settings a job was created with.
     *
     * @return array
     */
    private static function job_settings(array $job) {
        return array(
            'duration' => isset($job['duration']) ? (int) $job['duration'] : 5,
            'resolution' => isset($job['resolution']) ? (string) $job['resolution'] : '720P',
        );
    }

    /**
     * The newest in-flight job this user owns for one product.
     *
     * @return array|null
     */
    private static function active_job_for_user($product_id, $user_id) {
        foreach (PPG_Wan::job_index($product_id) as $id) {
            $job = PPG_Wan::load_job($id);
            if (!$job) { continue; }
            if ((int) $job['user_id'] !== (int) $user_id) { continue; }
            if (!PPG_Wan::is_active($job)) { continue; }
            return $job;
        }
        return null;
    }

    /**
     * The newest job this user owns for one product, finished or not.
     *
     * The index is stored newest first, so the first owned entry is the
     * newest one. An in-flight job always wins over a finished job, so the
     * recovery path never hides a render that is still running.
     *
     * @return array|null
     */
    private static function latest_job_for_user($product_id, $user_id) {
        $newest = null;
        $newest_active = null;
        foreach (PPG_Wan::job_index($product_id) as $id) {
            $job = PPG_Wan::load_job($id);
            if (!$job) { continue; }
            if ((int) $job['user_id'] !== (int) $user_id) { continue; }
            if ($newest === null) { $newest = $job; }
            if (PPG_Wan::is_active($job)) { $newest_active = $job; break; }
        }
        return $newest_active !== null ? $newest_active : $newest;
    }

    /**
     * A strict positive integer.
     *
     * Only a real integer or a string of digits is accepted. A float, a
     * boolean, a value with trailing junk and a value that does not fit in
     * a PHP integer are all refused.
     *
     * @param mixed $value Submitted value.
     * @return int The id, or 0 when the value is not a valid id.
     */
    private static function positive_id($value) {
        return PPG_Wan::positive_id($value);
    }

    private static function sanitize_job_id($raw) {
        if (!is_string($raw)) { return ''; }
        return preg_match('/^job_[a-f0-9]{16}$/', $raw) ? $raw : '';
    }
